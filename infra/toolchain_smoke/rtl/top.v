// 工具链自检用，不是学习材料。
//
// 这个设计的唯一作用是：在你写第一行自己的 Verilog 之前，证明
// 「综合 -> 布局布线 -> 打包 -> 烧录」整条链是通的。
// 它跑通 = 工具链没问题，之后任何失败都是你自己的代码或约束。
// 它跑不通 = 别去改代码，回来查工具链。
//
// 行为：6 个 LED 全灭（板上 LED 低电平点亮，输出 1 就是灭）。

module top (
    input  wire       clk,      // 27 MHz，接上是为了让布局布线有时钟可算
    output wire [5:0] led
);

    // 全灭。低电平点亮，所以输出全 1。
    assign led = 6'b111111;

endmodule
